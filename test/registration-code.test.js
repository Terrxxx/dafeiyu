import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startManager } from '../manager/server.js';
import { SiteSettings } from '../manager/site-settings.js';
import { passwordHash } from '../manager/accounts.js';

test('注册先完成图片验证与邮箱验证码，再设置密码；验证码不可重用',async t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'dfy-register-code-')),sent=[];
  const manager=await startManager({dataRoot:root,port:0,origins:[],runtime:async()=>({phase:'stopped'}),mailerFactory:()=>({verify:async()=>{},sendMail:async mail=>{sent.push(mail);return{accepted:[mail.to]};},close(){}})});
  t.after(async()=>{await manager.close();fs.rmSync(root,{recursive:true,force:true});});
  manager.registrationCodes.captchaCode=()=> '12345';
  manager.accounts.db.prepare('INSERT INTO users(username,password,role,created,email) VALUES(?,?,?,?,?)').run('owner',await passwordHash('owner-password-123'),'admin',Date.now(),'owner@example.test');
  const site=new SiteSettings(manager.accounts);site.save({...site.safe(),registrationMode:'open',smtp:{host:'smtp.example.test',port:465,encryption:'tls',user:'mail@example.test',password:'smtp-secret',from:'mail@example.test',senderName:'大肥鱼'}},'owner');
  const base='http://127.0.0.1:'+manager.server.address().port;
  const post=async(route,body)=>{const response=await fetch(base+route,{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify(body)});return {status:response.status,body:await response.json(),headers:response.headers};};
  const identity={username:'alice',email:'alice@example.test'};
  const password={password:'long-password-123',passwordConfirm:'long-password-123'};
  assert.equal((await post('/auth/register',{...identity,...password})).status,400);
  const challenge=await post('/auth/register/captcha',identity);
  assert.equal(challenge.status,200);
  assert.match(challenge.body.image,/^data:image\/png;base64,/);
  assert.equal((await post('/auth/register/code/request',{...identity,captchaChallenge:challenge.body.challenge,captchaAnswer:'00000'})).status,400);
  const captcha=await post('/auth/register/captcha',identity);
  const request=await post('/auth/register/code/request',{...identity,captchaChallenge:captcha.body.challenge,captchaAnswer:'12345'});
  assert.equal(request.status,200);
  assert.equal(sent.length,1);
  const code=sent[0].text.match(/注册验证码为：(\d{6})/)[1];
  assert.equal((await post('/auth/register/code/verify',{...identity,challenge:request.body.challenge,code:'000000'})).status,400);
  const verified=await post('/auth/register/code/verify',{...identity,challenge:request.body.challenge,code});
  assert.equal(verified.status,200);
  const created=await post('/auth/register',{...identity,...password,proof:verified.body.proof});
  assert.equal(created.status,201);
  assert.match(created.headers.get('set-cookie'),/dfy_session=/);
  assert.equal(manager.accounts.user('alice').email_verified,1);
  assert.equal(manager.accounts.user('alice').email_pending,0);
  assert.equal((await post('/auth/register',{...identity,...password,proof:verified.body.proof})).status,409);
});
